def get_regulations(zone_name: str, region: str = "") -> dict:
    """용도지역 규제 반환. region(시·도)이 REGION_ZONING에 있으면 조례값을 적용.

    반환 dict에 추가 필드:
      ordinance      — 적용된 근거 (조례명 또는 '국토계획법 시행령 상한')
      region_matched — 지자체 조례 수록 여부
    """
    if zone_name not in ZONING:
        raise ValueError(
            f"알 수 없는 용도지역: {zone_name}\n"
            f"선택 가능: {list(ZONING.keys())}"
        )
    base = dict(ZONING[zone_name])   # copy — 원본 오염 방지
    # 상위법(국토계획법 시행령) 상한 — 조례는 이 범위 안에서만 유효 (법령 위계)
    law_bcr_max, law_far_max = base["bcr"], base["far"]
    base["law_bcr_max"], base["law_far_max"] = law_bcr_max, law_far_max

    reg_tbl = REGION_ZONING.get(region or "")
    if reg_tbl and zone_name in reg_tbl:
        bcr, far = reg_tbl[zone_name]
        # ⚖ 상위법 우선: 조례 수록값이 시행령 상한을 넘으면 상한으로 제한
        #   (조례는 상위법 위임 범위 내에서만 효력 — 초과분은 무효)
        clamped = (bcr > law_bcr_max) or (far > law_far_max)
        base["bcr"] = min(bcr, law_bcr_max)
        base["far"] = min(far, law_far_max)
        verified = region in REGION_VERIFIED
        base["ordinance"] = (f"{region} 도시계획조례"
                             + ("" if verified else " (추정값)")
                             + (" · 시행령 상한으로 제한" if clamped else ""))
        base["region_matched"] = True
        base["ordinance_verified"] = verified
        base["law_clamped"] = clamped
    elif zone_name in TYPICAL_ORDINANCE:
        # 미수록 지역 → 전국 공통 조례 근사값 우선 적용 (시행령 상한보다 토지이음에 근접)
        bcr, far = TYPICAL_ORDINANCE[zone_name]
        clamped = (bcr > law_bcr_max) or (far > law_far_max)
        base["bcr"] = min(bcr, law_bcr_max)
        base["far"] = min(far, law_far_max)
        base["ordinance"] = ((f"{region} " if region else "") +
                             "일반 지자체 조례 기준(추정) — 토지이음 확인 권장")
        base["region_matched"] = True     # 조례(추정)를 적용했으므로 True로 노출
        base["ordinance_verified"] = False
        base["law_clamped"] = clamped
    else:
        base["ordinance"] = (f"국토계획법 시행령 상한 ({region} 조례 미수록)"
                             if region else "국토계획법 시행령 상한")
        base["region_matched"] = False
        base["ordinance_verified"] = False
        base["law_clamped"] = False
    return base


def max_height_at_north_distance(d_north: float) -> float:
    """정북방향 경계선으로부터 거리 d_north(m)일 때 허용 최대 높이 (건축법 시행령 §86)"""
    h_low = SOLAR_SLOPE_LOW * d_north
    if h_low <= SOLAR_BREAK_HEIGHT:
        return h_low
    # 9m 초과 구간은 slope 2.0 적용
    return SOLAR_SLOPE_HIGH * d_north


