def detect_region(address: str) -> str:
    """주소 문자열에서 시·도를 추출. 미식별 시 빈 문자열."""
    if not address:
        return ""
    a = address.strip()
    for full in REGION_ZONING.keys():
        if a.startswith(full):
            return full
    for alias, full in REGION_ALIASES.items():
        if a.startswith(alias):
            return full
    # 도 단위 (조례 미수록 → 시행령 상한 폴백 대상이지만 이름은 반환)
    for do in ("경기", "강원", "충청북", "충북", "충청남", "충남", "전라북", "전북",
               "전라남", "전남", "경상북", "경북", "경상남", "경남", "제주"):
        if a.startswith(do):
            return a.split()[0] if " " in a else do
    return ""

